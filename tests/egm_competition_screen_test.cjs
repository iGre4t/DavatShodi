const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const root = path.join(__dirname, '..', 'mini apps', 'Event Guest Manager');
const source = fs.readFileSync(path.join(root, 'period_draw.php'), 'utf8');
const css = source.match(/<style[^>]*>([\s\S]*?)<\/style>/)[1];
let markup = source.slice(source.indexOf('  <div id="competition-view"'), source.indexOf('  <script', source.indexOf('  <div id="competition-view"')));
markup = markup.replace(/<\?php for \(\$card[\s\S]*?<\?php endfor; \?>/, Array.from({length: 9}, (_, i) => `<button class="competition-card" data-card="${i+1}"><span class="competition-card-inner"><span class="competition-card-face competition-card-front">${i+1}</span><span class="competition-card-face competition-card-back"></span></span></button>`).join(''));
markup = markup.replace(/<\?=[\s\S]*?\?>/g, 'test').replace('data-endpoint="test"', 'data-endpoint="competition_prizes.php"').replace('class="page-view" hidden', 'class="page-view"');
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install();
    const requests = [];
    let confirmed = Array.from({length: 20}, (_, i) => ({rank: 2, card: 1, prizeName: `Prize ${i}`}));
    let pending = null;
    let keepConfirmedCards = true;
    await page.route('**/competition_prizes.php', async route => {
      const input = route.request().postDataJSON();
      requests.push(input);
      const action = input.action;
      if (action === 'reset') { confirmed = []; pending = null; }
      if (action === 'roll') pending = {card: input.card, prizeName: 'Final prize', rank: 2, token: 'test'};
      if (action === 'confirm') { confirmed.push(pending); pending = null; }
      const state = {status: 'ok', queue: [2,3,1], confirmed, pending, nextRank: 2, keepConfirmedCards, previewPrizes: ['Readable preview prize']};
      state.resetVersion = 'version';
      await route.fulfill({json: state});
    });
    await page.route('http://example.test/', route => route.fulfill({body: '<html></html>', contentType: 'text/html'}));
    await page.goto('http://example.test/');
    assert.ok(source.indexOf('id="competition-tab"') < source.indexOf('id="eligible-tab"'), 'Eligible tab is third');
    await page.setContent(`<style>${css}</style><body class="competition-mode"><nav class="page-header"><div class="page-menu"><a class="menu-item" id="draw-tab">قرعه‌کشی</a><a class="menu-item" id="competition-tab">جوایز رقابت‌ها</a><a class="menu-item" id="eligible-tab">واجدین شرایط</a></div></nav>${markup}</body>`);
    await page.addScriptTag({content: fs.readFileSync(path.join(root, 'competition-prizes.js'), 'utf8')});
    await page.waitForFunction(() => document.querySelector('#competition-progress').textContent.length > 0);
    for (const size of [{width:1920,height:1080},{width:1280,height:720},{width:1366,height:768}]) {
      await page.setViewportSize(size);
      const bounds = await page.locator('.competition-card, .competition-actions, .page-header').evaluateAll(elements => elements.map(el => {const r=el.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:r.width,height:r.height};}));
      assert.equal(await page.locator('.competition-card').count(), 9);
      const competitionHeader = await page.locator('.page-header').boundingBox();
      await page.evaluate(() => document.body.classList.remove('competition-mode'));
      const drawHeader = await page.locator('.page-header').boundingBox();
      assert.deepEqual(competitionHeader, drawHeader, 'Header stays in the same position as the draw tab');
      await page.evaluate(() => document.body.classList.add('competition-mode'));
      const shell = await page.locator('.competition-shell').boundingBox();
      assert.ok(shell.width <= 1120 && shell.x >= 60 && shell.y >= competitionHeader.y + competitionHeader.height + 20, 'Stage shell has side margins and space under the menu');
      for (const r of bounds) assert.ok(r.x>=0 && r.y>=0 && r.right<=size.width && r.bottom<=size.height && r.height>0, JSON.stringify({size,r}));
      assert.ok(await page.evaluate(() => document.documentElement.scrollHeight > innerHeight), 'Confirmed prizes flow below the stage');
      assert.equal(await page.locator('#competition-history').evaluate(el=>getComputedStyle(el).maxHeight), 'none');
      assert.ok(!(await page.locator('#competition-view').innerText()).includes('رتبه'));
      if (process.argv.includes('--preview') && size.width === 1280) await page.screenshot({path:path.join(__dirname,'../outputs/competition-layout-preview.png')});
    }
    await page.locator('#competition-reset').click();
    await page.waitForFunction(() => document.querySelector('#competition-history').children.length === 0);
    const standaloneResetCount = requests.filter(r => r.action === 'reset').length;
    const standaloneResetResponse = page.waitForResponse(response => response.url().endsWith('competition_prizes.php') && response.request().postDataJSON().action === 'reset');
    await page.keyboard.press('Shift+Delete');
    await standaloneResetResponse;
    assert.equal(requests.filter(r => r.action === 'reset').length, standaloneResetCount + 1, 'Competition shortcut works without the main draw keyboard handler');
    await page.keyboard.press('Shift+8');
    assert.equal(await page.locator('[data-card="8"]').evaluate(el => el.classList.contains('selected')), true);
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('.competition-card.charging'));
    await page.clock.runFor(800);
    assert.equal(await page.locator('.competition-card.flipped').count(), 0, 'Other cards never flip during suspense');
    assert.equal(await page.locator('[data-card="8"]').evaluate(el => el.classList.contains('flipped')), false);
    await page.clock.runFor(50);
    assert.equal(await page.locator('[data-card="8"]').evaluate(el => el.classList.contains('charging')), true, 'Selected card builds suspense before revealing');
    await page.clock.runFor(4700);
    assert.equal(await page.locator('.competition-reveal-effects.burst').count(), 1, 'Light spreads across the page before the reveal');
    assert.equal(await page.locator('.competition-card.flipped').count(), 0);
    if (process.argv.includes('--preview')) await page.screenshot({path:path.join(__dirname,'../outputs/competition-burst-preview.png')});
    await page.clock.runFor(600);
    assert.equal(await page.locator('.competition-confetti').count(), 72, 'Blue and orange confetti launches at reveal');
    if (process.argv.includes('--preview')) await page.screenshot({path:path.join(__dirname,'../outputs/competition-reveal-preview.png')});
    await page.clock.runFor(7000);
    assert.equal(await page.locator('.competition-card.flipped').count(), 1);
    assert.equal(await page.locator('[data-card="8"] .competition-card-back').textContent(), 'Final prize');
    assert.equal(await page.locator('#competition-confirm').isEnabled(), true);
    await page.locator('#competition-confirm').focus();
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#competition-confirm').disabled);
    await page.clock.runFor(8000);
    await page.waitForFunction(() => !document.querySelector('#competition-confirm').disabled);
    assert.equal(requests.filter(r => r.action === 'roll').length, 2, 'Enter rerolls even when confirmation has focus');
    assert.equal(requests.filter(r => r.action === 'confirm').length, 0, 'Enter never confirms');
    assert.equal(requests.filter(r => r.action === 'roll')[1].token, 'test');
    await page.keyboard.press('Space');
    await page.waitForFunction(() => document.querySelector('#competition-confirm').disabled);
    assert.equal(requests.filter(r => r.action === 'confirm').length, 1, 'Space confirms');
    await page.waitForFunction(() => document.querySelector('[data-card="8"]').disabled);
    assert.equal(await page.locator('[data-card="8"] .competition-card-back').textContent(), 'Final prize');
    assert.ok(await page.locator('[data-card="8"]').evaluate(el => el.classList.contains('flipped')));
    await page.keyboard.press('Shift+8');
    assert.equal(await page.locator('[data-card="8"]').evaluate(el => el.classList.contains('selected')), false);
    await page.keyboard.press('Shift+9');
    await page.keyboard.press('Enter');
    await page.clock.runFor(8000);
    await page.waitForFunction(() => !document.querySelector('#competition-confirm').disabled);
    assert.equal(await page.locator('[data-card="8"] .competition-card-back').textContent(), 'Final prize', 'Later animations preserve confirmed prizes');
    assert.ok(await page.locator('[data-card="8"]').evaluate(el => el.classList.contains('flipped')));
    await page.evaluate(() => window.dispatchEvent(new Event('egmcompetitionopen')));
    await page.waitForFunction(() => document.querySelector('[data-card="8"]').disabled);
    await page.evaluate(() => window.dispatchEvent(new Event('egmcompetitionreset')));
    await page.waitForFunction(() => document.querySelector('#competition-history').children.length === 0);
    assert.equal(await page.locator('.competition-card.flipped').count(), 0, 'Reset releases confirmed cards');
    assert.equal(requests.find(r => r.action === 'reset').version, 'version');
    const keyboardStart = source.indexOf('      document.addEventListener("keydown", (event) => {');
    const keyboardEnd = source.indexOf('      drawTab.addEventListener', keyboardStart);
    await page.evaluate(() => {
      const nav = document.querySelector('.page-menu');
      [...nav.children].forEach((tab, index) => {
        tab.addEventListener('click', () => {
          [...nav.children].forEach(item => item.classList.toggle('active', item === tab));
        });
      });
      nav.querySelector('#competition-tab').classList.add('active');
    });
    await page.addScriptTag({content: `(() => {
      const drawTab=document.querySelector('#draw-tab'), eligibleTab=document.querySelector('#eligible-tab'), competitionTab=document.querySelector('#competition-tab');
      const drawView={hidden:true}, competitionView=document.querySelector('#competition-view');
      const resetDraw=()=>{}, drawBusy=false, rollBtn={}, confirmBtn={};
      ${source.slice(keyboardStart, keyboardEnd)}
    })();`});
    await page.keyboard.press('Shift+ArrowLeft');
    assert.equal(await page.locator('#draw-tab').evaluate(el => el.classList.contains('active')), true);
    await page.keyboard.press('Shift+ArrowRight');
    assert.equal(await page.locator('#competition-tab').evaluate(el => el.classList.contains('active')), true);
    const resetCount = requests.filter(r => r.action === 'reset').length;
    const resetResponse = page.waitForResponse(response => response.url().endsWith('competition_prizes.php') && response.request().postDataJSON().action === 'reset');
    await page.keyboard.press('Shift+Delete');
    await resetResponse;
    await page.waitForFunction(() => document.querySelector('#competition-status').textContent.includes('بازنشانی'));
    assert.equal(requests.filter(r => r.action === 'reset').length, resetCount + 1, 'Shift+Delete resets the active prize tab');
    await page.emulateMedia({reducedMotion: 'reduce'});
    await page.keyboard.press('Shift+5');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('.competition-card.charging'));
    await page.clock.runFor(1000);
    assert.equal(await page.locator('[data-card="5"] .competition-card-back').textContent(), 'Final prize');
    assert.equal(await page.locator('#competition-confirm').isEnabled(), true, 'Reduced motion reveals promptly');
    assert.equal(await page.locator('.competition-reveal-effects').count(), 0, 'Reduced motion removes the effects layer');
    keepConfirmedCards = false;
    await page.keyboard.press('Space');
    await page.waitForFunction(() => document.querySelector('#competition-confirm').hidden);
    assert.equal(await page.locator('[data-card="5"]').isEnabled(), true, 'Reusable confirmed card is selectable');
    assert.equal(await page.locator('[data-card="5"]').evaluate(el => el.classList.contains('flipped')), false, 'Reusable card hides the prize after confirmation');
    assert.equal(await page.locator('#competition-history').locator('div').count(), 1, 'History survives card concealment');
    await page.keyboard.press('Shift+5');
    assert.equal(await page.locator('[data-card="5"]').evaluate(el => el.classList.contains('selected')), true);
    await page.evaluate(() => window.dispatchEvent(new Event('egmcompetitionopen')));
    await page.waitForFunction(() => document.querySelector('[data-card="5"]').classList.contains('selected'));
    assert.equal(await page.locator('[data-card="5"]').evaluate(el => el.classList.contains('flipped')), false, 'Refresh keeps reusable cards hidden');
    assert.deepEqual(errors, [], 'Animation and sound produce no browser errors');
    assert.ok(!source.includes('href="/panel.php">بازگشت به پنل'));
    console.log('PASS: videowall layout, card shortcuts, Enter reroll, Space confirmation, tab navigation and Shift+Delete reset.');
  } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
